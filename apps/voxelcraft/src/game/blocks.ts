const TIER_RANK: Record<string, number> = {
  none: 0,
  wood: 1,
  stone: 2,
  gold: 2,
  iron: 3,
  diamond: 4,
  netherite: 5,
};

export function canHarvestBlock(blockId: number, heldItemId: ItemId | null): boolean {
  const block = BLOCKS[blockId];
  if (!block || block.hardness < 0) return false;
  if (!block.requiresTool) return true;
  if (heldItemId === null) return false;
  const item = getItemDef(heldItemId);
  if (item?.toolCategory !== block.tool) return false;
  if (block.minPickaxeTier) {
    const heldRank = TIER_RANK[item?.toolTier ?? 'none'] ?? 0;
    const reqRank = TIER_RANK[block.minPickaxeTier] ?? 0;
    return heldRank >= reqRank;
  }
  return true;
}

export function getMiningSpeedMultiplier(blockId: number, heldItemId: ItemId | null): number {
  const block = BLOCKS[blockId];
  if (!block || block.hardness < 0) return 0;
  const item = heldItemId !== null ? getItemDef(heldItemId) : undefined;
  // Shears slice Leaves and Wool ultra fast
  if (item?.toolCategory === 'shears' && (block.isLeaves || WOOL_IDS.includes(blockId))) {
    return 6.0;
  }
  const matchingTool = item?.toolCategory && item.toolCategory === block.tool;
  if (block.requiresTool && !matchingTool) {
    return 0.2;
  }
  if (matchingTool && item?.miningMultiplier) {
    return item.miningMultiplier;
  }
  return 1.0;
}

export function getWeaponDamage(heldItemId: ItemId | null): number {
  const item = heldItemId !== null ? getItemDef(heldItemId) : undefined;
  return item?.attackDamage ?? 1;
}

export function getToolCategory(heldItemId: ItemId | null): ToolCategory {
  const item = heldItemId !== null ? getItemDef(heldItemId) : undefined;
  return item?.toolCategory ?? 'none';
}

export function calculateTotalArmorPoints(armor: ArmorSlots): number {
  let total = 0;
  for (const slot of armor) {
    if (!slot) continue;
    total += getItemDef(slot.id)?.armorPoints ?? 0;
  }
  return Math.min(20, total);
}

/**
 * Damage reduction formula from armor for combat/projectile/explosion damage.
 */
export function applyArmorDamageReduction(rawDamage: number, armorPoints: number): number {
  const reduction = Math.min(20, Math.max(0, armorPoints)) * 0.032;
  return Math.max(0.5, rawDamage * (1 - reduction));
}
